// ───────────────────────────── Phase T6: generation jobs, diagnostics, elective blocks ─────────────────────────────
// See .agents/edunova/phase-t6-sessions-jobs.md and server/src/modules/timetable/{jobs,diagnostics,electives}.ts.

const JOB_TERMINAL: TimetableGenerationJob['status'][] = ['COMPLETED', 'FAILED', 'CANCELLED']

/**
 * Wraps POST /generation-jobs (create+run) with a poll loop against GET /generation-jobs/:id — the job
 * currently completes synchronously within the create call (see jobs.ts), so the poll loop typically sees a
 * terminal status on its very first tick and stops immediately; it's still wired for real, since a job's
 * status/progress/currentStage are recorded faithfully row-by-row specifically so this same polling
 * mechanism keeps working unchanged once generation genuinely runs in the background at whole-school scale.
 */
export function useGenerationJob() {
  const [job, setJob] = useState<TimetableGenerationJob | null>(null)
  const [busy, setBusy] = useState<'run' | 'commit' | 'regenerate' | null>(null)
  const [error, setError] = useState<string | null>(null)
  const pollRef = useRef<number | null>(null)

  const stopPoll = useCallback(() => { if (pollRef.current) { window.clearInterval(pollRef.current); pollRef.current = null } }, [])
  useEffect(() => stopPoll, [stopPoll])

  const poll = useCallback((id: string) => {
    stopPoll()
    pollRef.current = window.setInterval(async () => {
      try {
        const res = await api.get<{ item: TimetableGenerationJob }>(`/timetable/generation-jobs/${id}`)
        setJob(res.item)
        if (JOB_TERMINAL.includes(res.item.status)) stopPoll()
      } catch { stopPoll() }
    }, 1000) as unknown as number
  }, [stopPoll])

  const run = useCallback(async (body: {
    termId: string; cohortIds: string[]; mode: AutoGenerateMode
    preferenceProfileName?: PreferenceProfileName; timeBudgetMsPerGroup?: number; seed?: number
  }) => {
    setBusy('run'); setError(null); setJob(null)
    try {
      const res = await api.post<{ item: TimetableGenerationJob }>('/timetable/generation-jobs', body)
      setJob(res.item)
      if (!JOB_TERMINAL.includes(res.item.status)) poll(res.item.id)
      return res.item
    } catch (e) { setError(errorMessage(e)); return null } finally { setBusy(null) }
  }, [poll])

  const commit = useCallback(async (jobId: string) => {
    setBusy('commit')
    try { return await api.post<AutoGenerateCommitResult>('/timetable/generation-jobs/commit', { jobId }) }
    finally { setBusy(null) }
  }, [])

  const regenerate = useCallback(async (jobId: string) => {
    setBusy('regenerate'); setError(null)
    try {
      const res = await api.post<RegenerateJobResult>(`/timetable/generation-jobs/${jobId}/regenerate`)
      setJob(res.job)
      if (!JOB_TERMINAL.includes(res.job.status)) poll(res.job.id)
      return res
    } catch (e) { setError(errorMessage(e)); return null } finally { setBusy(null) }
  }, [poll])

  const reset = useCallback(() => { stopPoll(); setJob(null); setError(null) }, [stopPoll])

  return { job, busy, error, run, commit, regenerate, reset }
}

