/** Resolves display strings for an entry from the academic slice, preferring names the server already attached. */
export function useEntryLookup() {
  const { classSubjects, subjectById, classById, rooms } = useAcademic()
  const { db } = useStore()
  return useMemo(() => {
    const csById = new Map(classSubjects.map(cs => [cs.id, cs]))
    const roomById = new Map(rooms.map(r => [r.id, r]))
    const userById = new Map(db.users.map(u => [u.id, u]))
    const subjectRec = (e: TimetableEntryView) => { const cs = csById.get(e.classSubjectId); return cs ? subjectById.get(cs.subjectId) : undefined }
    return {
      subjectOf: (e: TimetableEntryView) => e.subjectName ?? subjectRec(e)?.name ?? 'Subject',
      colorOf: (e: TimetableEntryView) => subjectRec(e)?.color ?? '#6366f1',
      teacherOf: (e: TimetableEntryView) => e.teacherName ?? userById.get(e.teacherId ?? csById.get(e.classSubjectId)?.teacherId ?? '')?.name,
      roomOf: (e: TimetableEntryView) => e.roomName ?? (e.roomId ? roomById.get(e.roomId)?.name : undefined),
      classLabelOf: (e: TimetableEntryView) => e.classLabel ?? classById.get(e.classId)?.label,
      userName: (id?: string) => (id ? userById.get(id)?.name : undefined),
    }
  }, [classSubjects, subjectById, classById, rooms, db.users])
}
export type EntryLookup = ReturnType<typeof useEntryLookup>

// ───────────────────────────── Phase 26: auto-generate ─────────────────────────────
// See server/src/modules/timetable/autogen.ts for the exact draft/commit shapes this wraps. The endpoint
// itself never writes anything — `generate` only returns a proposal, `commit` is the one call that
// actually creates TimetableEntry rows, so the Timetable Builder always shows the draft as a distinct,
// unsaved view before either of those runs.

/** Wraps the two auto-generate POSTs with shared busy state so the builder screen doesn't duplicate it. */
export function useAutoGenerate() {
  const [busy, setBusy] = useState<'generate' | 'commit' | null>(null)
  // Phase T4 introduced the Cohort/TeachingRequirement/TeachingAssignment-scoped solver behind `cohortIds`;
  // Phase T10 §2 retired the legacy ClassSubject-scoped generator that used to run when it was omitted, so
  // `cohortIds` is required now (non-empty, enforced server-side by the schema).
  const generate = async (body: { cohortIds: string[]; termId: string; mode: AutoGenerateMode }) => {
    setBusy('generate')
    try { return await api.post<AutoGenerateResult>('/timetable/auto-generate', body) } finally { setBusy(null) }
  }
  const commit = async (body: { termId: string; mode: AutoGenerateMode; draftEntries: AutoGenerateDraftEntry[] }) => {
    setBusy('commit')
    try { return await api.post<AutoGenerateCommitResult>('/timetable/auto-generate/commit', body) } finally { setBusy(null) }
  }
  return { busy, generate, commit }
}

/**
 * Fetches each class's live grid, keyed by classId — used by the auto-generate draft review to render
 * pre-existing periods alongside newly generated ones in `fill-empty` mode (so the admin sees the whole
 * resulting grid, not just what's new). Not needed for `full-regenerate`, whose draft already stands alone.
 */
export function useGridsFor(classIds: string[], termId: string, enabled: boolean) {
  const key = enabled && termId ? classIds.slice().sort().join(',') : ''
  const [state, setState] = useState<{ key: string; data: Map<string, TimetableEntryView[]> }>({ key: '', data: new Map() })
  useEffect(() => {
    if (!key) return
    let cancelled = false
    Promise.all(classIds.map(id =>
      api.get<ClassTimetable>(`/timetable?classId=${encodeURIComponent(id)}&termId=${encodeURIComponent(termId)}`).then(d => [id, d.entries] as const),
    ))
      .then(pairs => { if (!cancelled) setState({ key, data: new Map(pairs) }) })
      .catch(() => { if (!cancelled) setState({ key, data: new Map() }) })
    return () => { cancelled = true }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key, termId])
  return state.key === key ? state.data : new Map<string, TimetableEntryView[]>()
}

