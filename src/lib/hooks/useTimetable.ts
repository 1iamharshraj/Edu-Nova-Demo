/** Every TeachingRequirement for one cohort (per-cohort config screen). */
export function useTeachingRequirements(cohortId: string | undefined) {
  const path = cohortId ? `/timetable/teaching-requirements?cohortId=${encodeURIComponent(cohortId)}` : null
  const { data, loading, error, reload } = useFetch<{ items: TeachingRequirement[] }>(path)
  const [busy, setBusy] = useState(false)

  const run = useCallback(async <T,>(fn: () => Promise<T>, okMsg?: string): Promise<T | null> => {
    setBusy(true)
    try {
      const out = await fn()
      reload()
      if (okMsg) toast.success(okMsg)
      return out
    } catch (e) { toast.error(errorMessage(e)); return null } finally { setBusy(false) }
  }, [reload])

  const create = useCallback((body: {
    subjectId: string; requiredPeriodsPerWeek: number; sessionDuration: SessionDuration
    roomRequirement: RoomRequirementKind; specificRoomId?: string; labDoubleAllowed: boolean
  }, okMsg?: string) => run(() =>
    api.post<{ item: TeachingRequirement }>('/timetable/teaching-requirements', { cohortId, ...body }).then(r => r.item), okMsg), [cohortId, run])

  const update = useCallback((id: string, body: Partial<Pick<TeachingRequirement,
    'requiredPeriodsPerWeek' | 'sessionDuration' | 'roomRequirement' | 'specificRoomId' | 'labDoubleAllowed'>>, okMsg?: string) =>
    run(() => api.patch<{ item: TeachingRequirement }>(`/timetable/teaching-requirements/${id}`, body).then(r => r.item), okMsg), [run])

  const remove = useCallback((id: string, okMsg?: string) =>
    run(() => api.del<{ ok: true }>(`/timetable/teaching-requirements/${id}`), okMsg), [run])

  const seedFromClassSubjects = useCallback((academicYearId: string, okMsg?: string) =>
    run(() => api.post<{ created: number; requirementIds: string[] }>('/timetable/teaching-requirements/seed-from-class-subjects', { cohortId, academicYearId }), okMsg), [cohortId, run])

  return { items: data?.items ?? [], loading, error, reload, busy, create, update, remove, seedFromClassSubjects }
}

