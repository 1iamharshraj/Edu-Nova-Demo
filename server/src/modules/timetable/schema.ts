// ───────────────────────── Phase T8 — What-If / partial re-optimization ─────────────────────────
// See phase-t8-what-if.md. A changeEvent names one real, already-applied-or-about-to-be-applied change
// (a teacher's TeacherAvailability rows already reflect an absence, a TeachingRequirement was already
// created/patched via the existing endpoints, etc.) — what-if's own job is purely to compute + apply the
// MINIMAL timetable ripple that change causes, never to be the place that mutates the triggering entity
// itself (reuse what's already there, per the ground rules).
