// ───────────────────────────── Phase 26: auto-generate ─────────────────────────────

export const autoGenerateMode = z.enum(['fill-empty', 'full-regenerate'])

// classId omitted → generate for every class in the term's academic year. Phase T4 (phase-t4-solver-
// core.md §4) adds `cohortIds`: when given (non-empty), generation runs the new Cohort/TeachingRequirement/
// TeachingAssignment-scoped path (./solver.ts) instead of the legacy ClassSubject-scoped one — `classId`
// is ignored in that case. Omitting `cohortIds` (the default) keeps Phase 26's existing behavior byte-
// identical, so the currently-shipped "Auto-Generate" UI needs zero changes.
// Phase T10 §2 — `classId`-scoped (or fully-omitted, "every class in the year") generation was Phase 26's
// legacy ClassSubject-scoped generator, retired now that the Cohort/TeachingRequirement-scoped solver
// (T4+) covers the same ground (every class has an auto-generated 1:1 "section cohort" per D2, so "this
// class" and "all classes" are just "this class's cohort" / "every cohort" from the caller's side) plus
// soft-constraint refinement, diagnostics, and shared/elective sessions the legacy path never had.
// `cohortIds` is required going forward — see phase-t10-migration.md §2.
export const autoGenerateBody = z.object({
  cohortIds: z.array(idStr).min(1),
  termId: idStr,
  mode: autoGenerateMode,
})

// The commit endpoint re-validates everything (see service.ts#commitAutoGenerate), so the draft entry
// shape is entryInput plus the classId each draft row belongs to (a generate call can span many classes).
export const autoGenerateDraftEntry = entryInput.extend({ classId: idStr })

export const autoGenerateCommitBody = z.object({
  termId: idStr,
  mode: autoGenerateMode,
  draftEntries: z.array(autoGenerateDraftEntry),
})

